"""Generated rule catalogue (docs/RULES.md) and the field to rule map for CONTRACT.md."""

from __future__ import annotations

import json
from typing import Any

from sikka.conformance.context import RuleConfig
from sikka.conformance.fields import BASE_HEADER, BASE_RECORDS, specs
from sikka.conformance.registry import FAMILY_NAMES, REGISTRY, Example, Rule


def example_records(example: Example) -> tuple[dict[str, Any], dict[str, Any]]:
    """Failing and passing records: the base record with the example overrides applied."""
    base = dict(BASE_RECORDS[example.feed_type])

    def apply(overrides: dict[str, Any]) -> dict[str, Any]:
        out = dict(base)
        for key, value in overrides.items():
            if value is None:
                out.pop(key, None)
            else:
                out[key] = value
        return out

    return apply(example.failing), apply(example.passing)


def example_header(example: Example) -> dict[str, Any]:
    header = dict(BASE_HEADER) | {"feed_type": example.feed_type}
    header.update(example.header or {})
    return header


def rules_by_field() -> dict[str, list[str]]:
    """Map ``feed.field`` to the ids of rules that check it (``*`` expands to every field)."""
    out: dict[str, list[str]] = {}
    for rule in sorted(REGISTRY.values(), key=lambda r: r.id):
        for feed in rule.feed_types:
            names = list(specs(feed)) if "*" in rule.fields else list(rule.fields)
            for name in names:
                if name in specs(feed):
                    out.setdefault(f"{feed}.{name}", []).append(rule.id)
    return out


def _dumps(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=False)


def _rule_section(rule: Rule) -> list[str]:
    lines = [
        f"### `{rule.id}` {rule.title}",
        "",
        f"Severity: **{rule.severity}**. Scope: {rule.scope}. Feeds: "
        + ", ".join(f"`{f}`" for f in rule.feed_types)
        + "."
        + (f" Needs: {', '.join(rule.needs)}." if rule.needs else ""),
        "",
        rule.description,
        "",
        f"Why it matters: {rule.rationale}",
        "",
        f"How to fix: {rule.fix_hint}",
        "",
    ]
    ex = rule.example
    if ex is None:
        lines += [
            "Example: this rule looks at a series or at several feeds together, so a single "
            "record cannot show it. Its tests in `tests/conformance` build the failing and "
            "passing cases.",
            "",
        ]
        return lines
    failing, passing = example_records(ex)
    if ex.header:
        lines += [
            "Failing header (differences from a valid header):",
            "",
            "```json",
            _dumps(ex.header),
            "```",
            "",
            "Passing header: the same header with valid values, for example",
            "",
            "```json",
            _dumps({k: BASE_HEADER[k] for k in ex.header if k in BASE_HEADER}),
            "```",
            "",
        ]
        return lines
    changed = {
        k: failing.get(k) for k in set(failing) | set(passing) if failing.get(k) != passing.get(k)
    }
    lines += [
        "Failing record (fields that differ from the passing record):",
        "",
        "```json",
        _dumps({k: (v if v is not None else "(absent)") for k, v in sorted(changed.items())}),
        "```",
        "",
        "Passing record:",
        "",
        "```json",
        _dumps(passing),
        "```",
        "",
    ]
    return lines


def render_rules_md() -> str:
    c = RuleConfig()
    lines = [
        "# Rule catalogue",
        "",
        "> Generated by `sikka docs build` from the rule registry in `sikka.conformance`. Do not "
        "edit by hand.",
        "",
        "Every example below is synthetic. Rules check feeds against contract v1.0.0. A record "
        "flagged by a privacy rule (family P) is quarantined: its values are never shown in "
        "reports, examples or maps.",
        "",
        "Thresholds: " + ", ".join(f"`{k}` = {v}" for k, v in sorted(c.__dict__.items())) + ".",
        "",
        "| Rule | Family | Severity | Scope | Title |",
        "| --- | --- | --- | --- | --- |",
    ]
    for rule in sorted(REGISTRY.values(), key=lambda r: r.id):
        lines.append(
            f"| `{rule.id}` | {FAMILY_NAMES[rule.family]} | {rule.severity} | {rule.scope} | "
            f"{rule.title} |"
        )
    lines.append("")
    for code, name in FAMILY_NAMES.items():
        lines += [f"## {name} ({code})", ""]
        for rule in sorted(REGISTRY.values(), key=lambda r: r.id):
            if rule.family == code:
                lines += _rule_section(rule)
    return "\n".join(lines)
