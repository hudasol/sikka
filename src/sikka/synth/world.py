"""Assemble the synthetic world, its producer feeds and the hidden ground truth."""

from __future__ import annotations

import copy
import math
from dataclasses import dataclass, field
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

from sikka.contract.feedfile import FORMAT_SUFFIX, FeedFormat, render_feed
from sikka.core import LOCAL_TZ, format_utc, round_floats, stable_json_dumps
from sikka.synth.config import CORRIDORS, PRODUCERS, WorldConfig
from sikka.synth.crashes import SegmentHazard, TrueCrash, build_crashes, build_hazard
from sikka.synth.exposure import (
    Station,
    choose_stations,
    count_week_start_utc,
    station_counts,
    true_aadt,
)
from sikka.synth.network import SegmentTruth, build_network
from sikka.synth.producers import observe

SYNTHETIC_NOTE = "Synthetic data generated by Sikka. No real crash, traffic or road records."


@dataclass
class Feed:
    """One feed file before it is written: header, records and fault bookkeeping."""

    name: str
    feed_type: str
    producer_id: str
    fmt: FeedFormat
    header: dict[str, Any]
    records: list[dict[str, Any]]
    series_faults: list[tuple[str, str]] = field(default_factory=list)
    file_faults: list[str] = field(default_factory=list)

    @property
    def filename(self) -> str:
        return self.name + FORMAT_SUFFIX[self.fmt]


@dataclass
class World:
    config: WorldConfig
    segments: list[SegmentTruth]
    stations: list[Station]
    hazard: dict[str, SegmentHazard]
    b0: float
    crashes: list[TrueCrash]
    feeds: list[Feed]
    injected: dict[str, float] = field(default_factory=dict)

    def feed(self, name: str) -> Feed:
        for f in self.feeds:
            if f.name == name:
                return f
        raise KeyError(name)

    def copy(self) -> World:
        return World(
            self.config,
            self.segments,
            self.stations,
            self.hazard,
            self.b0,
            self.crashes,
            copy.deepcopy(self.feeds),
            dict(self.injected),
        )


def crash_period(config: WorldConfig) -> tuple[datetime, datetime]:
    start = datetime(config.first_year, 1, 1, tzinfo=LOCAL_TZ).astimezone(UTC)
    end = datetime(config.last_year + 1, 1, 1, tzinfo=LOCAL_TZ).astimezone(UTC)
    return start, end


def _header(
    producer: str,
    feed_type: str,
    generated: datetime,
    period: tuple[datetime, datetime],
    config: WorldConfig,
) -> dict[str, Any]:
    return {
        "producer_id": producer,
        "feed_type": feed_type,
        "contract_version": "1.0.0",
        "generated_at": format_utc(generated),
        "licence": config.licence,
        "synthetic": True,
        "record_count": 0,
        "period_start": format_utc(period[0]),
        "period_end": format_utc(period[1]),
    }


def build_world(config: WorldConfig) -> World:
    """Generate the clean synthetic world for a seed. No faults are injected here."""
    segments = build_network(config)
    by_id = {s.segment_id: s for s in segments}
    aadt = true_aadt(config, segments)
    stations = choose_stations(config, segments)
    b0, hazard = build_hazard(config, segments, aadt)
    crashes = build_crashes(config, segments, hazard)
    period = crash_period(config)
    crash_generated = period[1] + timedelta(days=20, hours=6)
    feeds: list[Feed] = []

    registry_generated = datetime(config.last_year + 1, 1, 5, 6, tzinfo=UTC)
    registry_period = (datetime(2020, 1, 1, tzinfo=UTC), registry_generated)
    for owner in sorted({c.owner for c in CORRIDORS}):
        rows: list[dict[str, Any]] = []
        for i, seg in enumerate(s for s in segments if s.corridor.owner == owner):
            row = dict(seg.registry_record("2020-01-01T00:00:00Z"))
            row["__meta__"] = {"order": (i,)}
            rows.append(row)
        feeds.append(
            Feed(
                f"road_segments_{owner.lower()}",
                "road_segments",
                owner,
                "geojson",
                _header(owner, "road_segments", registry_generated, registry_period, config),
                rows,
            )
        )

    for profile in PRODUCERS:
        records = observe(config, profile, crashes, by_id, period)
        feeds.append(
            Feed(
                f"crash_records_{profile.producer_id.lower()}",
                "crash_records",
                profile.producer_id,
                "csv" if profile.crash_format == "csv" else "ndjson",
                _header(profile.producer_id, "crash_records", crash_generated, period, config),
                records,
            )
        )

    counts = station_counts(config, segments, stations, aadt)
    week_start = count_week_start_utc(config)
    week = (week_start, week_start + timedelta(days=config.count_days))
    counts_generated = week[1] + timedelta(days=1, hours=2)
    for owner in sorted({s.owner for s in stations}):
        rows = [r for st in stations if st.owner == owner for r in counts[st.station_id]]
        feeds.append(
            Feed(
                f"traffic_counts_{owner.lower()}",
                "traffic_counts",
                owner,
                "csv",
                _header(owner, "traffic_counts", counts_generated, week, config),
                rows,
            )
        )
    return World(config, segments, stations, hazard, b0, crashes, feeds)


def _order_key(record: dict[str, Any]) -> tuple[Any, ...]:
    meta = record.get("__meta__", {})
    return tuple(meta.get("order", ()))


def finalise_feed(feed: Feed) -> tuple[str, list[dict[str, Any]]]:
    """Render a feed and return its text with the final record order."""
    records = sorted(feed.records, key=_order_key)
    header = dict(feed.header)
    if "record_count_override" in header:
        header["record_count"] = header.pop("record_count_override")
    else:
        header["record_count"] = len(records)
    return render_feed(feed.fmt, header, records), records


def truth_documents(world: World, finals: dict[str, list[dict[str, Any]]]) -> dict[str, Any]:
    """Hidden truth: segment hazards, record to true crash map and fault locations."""
    record_map: list[dict[str, Any]] = []
    fault_rows: list[dict[str, Any]] = []
    true_to_records: dict[str, list[tuple[str, str, int]]] = {}
    for feed in world.feeds:
        for row, record in enumerate(finals[feed.name], 1):
            meta = record.get("__meta__", {})
            true_id = meta.get("true_id")
            if true_id:
                record_map.append({"file": feed.filename, "row": row, "true_id": true_id})
                true_to_records.setdefault(true_id, []).append(
                    (feed.producer_id, feed.filename, row)
                )
            for fault_id in meta.get("faults", []):
                fault_rows.append(
                    {"fault_id": fault_id, "file": feed.filename, "unit": "record", "row": row}
                )
        for fault_id, series in feed.series_faults:
            fault_rows.append(
                {"fault_id": fault_id, "file": feed.filename, "unit": "series", "series": series}
            )
        for fault_id in feed.file_faults:
            fault_rows.append({"fault_id": fault_id, "file": feed.filename, "unit": "file"})
    # Every record whose crash is also reported by another producer is a cross feed duplicate.
    for refs in true_to_records.values():
        producers = {p for p, _, _ in refs}
        if len(producers) > 1:
            for _, filename, row in refs:
                fault_rows.append(
                    {"fault_id": "F20", "file": filename, "unit": "record", "row": row}
                )
    fault_rows.sort(
        key=lambda r: (r["fault_id"], r["file"], r["unit"], r.get("row", 0), r.get("series", ""))
    )
    # Remove exact duplicates (an injected F20 copy is also a natural duplicate).
    unique: list[dict[str, Any]] = []
    for r in fault_rows:
        if not unique or unique[-1] != r:
            unique.append(r)
    stations = {s.segment_id: s.station_id for s in world.stations}
    segments = [
        {
            "segment_id": s.segment_id,
            "corridor": s.corridor.code,
            "aadt": world.hazard[s.segment_id].aadt,
            "spf_mean_per_year": world.hazard[s.segment_id].mu,
            "hazard_multiplier": world.hazard[s.segment_id].multiplier,
            "true_rate_per_year": world.hazard[s.segment_id].rate,
            "true_counts_by_year": list(world.hazard[s.segment_id].counts),
            "blackspot": world.hazard[s.segment_id].multiplier > 1.0,
            "hotspot_fraction": world.hazard[s.segment_id].hotspot,
            "station_id": stations.get(s.segment_id),
        }
        for s in world.segments
    ]
    cfg = world.config
    return {
        "truth": {
            "note": SYNTHETIC_NOTE + " Hidden truth for evaluation only.",
            "seed": cfg.seed,
            "spf": {
                "b0": world.b0,
                "aadt_exponent": cfg.spf_aadt_exponent,
                "length_exponent": cfg.spf_length_exponent,
                "class_effect": cfg.spf_class_effect,
                "lane_effect": cfg.spf_lane_effect,
                "dispersion_k": cfg.dispersion_k,
                "years": cfg.years,
            },
            "segments": segments,
            "true_crash_count": len(world.crashes),
            "injected_faults": world.injected,
        },
        "record_map": record_map,
        "faults": unique,
    }


def write_world(world: World, out_dir: Path) -> dict[str, Path]:
    """Write feeds to ``out_dir/feeds`` and truth to ``out_dir/ground_truth``."""
    feeds_dir = out_dir / "feeds"
    truth_dir = out_dir / "ground_truth"
    feeds_dir.mkdir(parents=True, exist_ok=True)
    truth_dir.mkdir(parents=True, exist_ok=True)
    written: dict[str, Path] = {}
    finals: dict[str, list[dict[str, Any]]] = {}
    for feed in world.feeds:
        text, records = finalise_feed(feed)
        finals[feed.name] = records
        path = feeds_dir / feed.filename
        path.write_bytes(text.encode("utf-8"))
        written[feed.filename] = path
    for name, doc in truth_documents(world, finals).items():
        path = truth_dir / f"{name}.json"
        path.write_bytes((stable_json_dumps(round_floats(doc), indent=1) + "\n").encode("utf-8"))
        written[f"ground_truth/{name}.json"] = path
    return written


def crash_total_check(world: World) -> float:
    """Ratio of realised true crashes to the configured target (diagnostic)."""
    return len(world.crashes) / world.config.target_total_crashes if world.crashes else math.nan
