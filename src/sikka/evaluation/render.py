"""Render docs/EVALUATION.md from results/*.json. Every number comes from those files."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from sikka.evaluation.predictions import RESULT_FILES, Results, judge

LIMITATIONS = [
    "All results hold for the synthetic world in this repository only. The world, the faults, "
    "the rules, the adapters and the ranking method were built by the same author, so agreement "
    "between them is expected to be better than on real feeds.",
    "Fault detection (E1) measures the faults in the catalogue. It says nothing about defects "
    "that were not anticipated.",
    "Entity resolution (E2) uses matching parameters that are assumptions, not fitted values; "
    "real producers may have larger time and location differences.",
    "The synthetic crash process has the same functional form as the safety performance "
    "function, which favours Empirical Bayes in E3. On real data the SPF would be misspecified "
    "to some degree.",
    "Daily traffic is constant across 2021 to 2025 in the synthetic world and is estimated from "
    "one week of counts; real exposure varies by season and year.",
    "Capture recapture assumes independent detection by producers; in the synthetic world "
    "detection is independent by construction, which real reporting is not.",
]


def load_results(results_dir: Path) -> Results:
    out: Results = {}
    for name in RESULT_FILES.values():
        path = results_dir / f"{name}.json"
        if path.is_file():
            out[name] = json.loads(path.read_text(encoding="utf-8"))
    perf = results_dir / "performance.json"
    if perf.is_file():
        out["performance"] = json.loads(perf.read_text(encoding="utf-8"))
    return out


def _iv(node: dict[str, Any] | None, digits: int = 3) -> str:
    if not node or node.get("estimate") is None:
        return "undefined"
    est, low, high = node["estimate"], node.get("low"), node.get("high")
    if low is None or high is None or node.get("n", 2) < 2:
        return f"{est:.{digits}f}"
    return f"{est:.{digits}f} ({low:.{digits}f} to {high:.{digits}f})"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return [*lines, ""]


def _e(node: dict[str, Any] | None) -> float | None:
    return None if not node or node.get("estimate") is None else float(node["estimate"])


def observations(results: Results) -> list[str]:
    """Plain statements comparing results, each built from numbers in the files."""
    out: list[str] = []
    e2 = results.get("e2_entity_resolution")
    if e2:
        for scenario, s in e2["summary"].items():
            naive = e2["naive_baseline"][scenario]
            pr_m, pr_n = _e(s["precision"]), _e(naive["precision"])
            re_m, re_n = _e(s["recall"]), _e(naive["recall"])
            if None in (pr_m, pr_n, re_m, re_n):
                continue
            better = "higher" if re_n > re_m else "lower"  # type: ignore[operator]
            out.append(
                f"E2 `{scenario}`: the naive baseline has {better} recall than the matcher "
                f"({re_n:.3f} against {re_m:.3f}) at precision {pr_n:.6f} against {pr_m:.6f}. "
                "On this synthetic world the matcher's abstention lowers recall without a "
                "material gain in precision."
                if re_n > re_m  # type: ignore[operator]
                else f"E2 `{scenario}`: the matcher has higher recall than the naive baseline "
                f"({re_m:.3f} against {re_n:.3f}) at precision {pr_m:.6f} against {pr_n:.6f}."
            )
    e3 = results.get("e3_blackspot_ranking")
    if e3:
        s = e3["summary"]
        ranked = {m: _e(s.get(f"{m}_recall_rankable")) for m in e3["methods"]}
        best = max((m for m in ranked if ranked[m] is not None), key=lambda m: ranked[m] or 0.0)
        text = (
            f"E3: the highest recall of planted blackspots with exposure comes from `{best}` "
            f"({ranked[best]:.3f})."
        )
        if best not in {"eb", "eb_qp"}:
            text += (
                " Empirical Bayes ranks by excess crashes, so a planted blackspot on a quiet "
                "or short segment, whose excess is small in absolute terms, can rank below "
                "busy segments with a modest excess."
            )
        out.append(text)
    return out


def render_evaluation(results: Results) -> str:
    verdicts = judge(results)
    hits = sum(v["verdict"] == "HIT" for v in verdicts)
    misses = sum(v["verdict"] == "MISS" for v in verdicts)
    pending = sum(v["verdict"] == "PENDING" for v in verdicts)
    seeds: list[int] = next((r["seeds"] for r in results.values() if "seeds" in r), [])
    lines = [
        "# Evaluation",
        "",
        "> Generated by `sikka docs build` from `results/*.json`, which `sikka eval` writes. Do "
        "not edit by hand; a test fails if this file differs from what the results produce.",
        "",
        "Synthetic data only. Every number below comes from the synthetic world in this "
        "repository; none describes real roads, crashes or producers.",
        "",
        "The experiments, metrics, seeds and predictions were fixed in "
        "[PREREGISTRATION.md](PREREGISTRATION.md) before any of these results existed. Means over "
        "seeds are shown with 95 percent Student t intervals in brackets. Implementation "
        "details settled after registration are listed in its dated amendments.",
        "",
        f"Seeds: {seeds[0]} to {seeds[-1]} ({len(seeds)} seeds)." if seeds else "Seeds: none run.",
        "",
        "## Predictions",
        "",
        f"{hits} hits, {misses} misses, {pending} pending.",
        "",
    ]
    lines += _table(
        ["Id", "Prediction", "Observed", "Verdict"],
        [[v["id"], v["text"], v["observed"], f"**{v['verdict']}**"] for v in verdicts],
    )
    if "e1_fault_detection" in results:
        e1 = results["e1_fault_detection"]
        rates = [f"{r:g}" for r in e1["rates"]]
        lines += [
            "## E1: fault detection",
            "",
            "Isolation: each fault injected alone, checked by its expected rules only. Recall, "
            "then precision, per injection rate.",
            "",
        ]
        rows = []
        for fid, f in sorted(e1["faults"].items()):
            row = [fid, f["title"], ", ".join(f"`{r}`" for r in f["expected_rules"])]
            row += [_iv(f["by_rate"][r]["recall"]) for r in rates]
            row += [_iv(f["by_rate"][r]["precision"]) for r in rates]
            rows.append(row)
        lines += _table(
            ["Fault", "Title", "Rules"]
            + [f"Recall at {r}" for r in rates]
            + [f"Precision at {r}" for r in rates],
            rows,
        )
        lines += [
            f"Schema only baseline (contract model validation) at {e1['baseline_rate']:g}, and the "
            f"combined scenario with every fault at {e1['combined_rate']:g} and every rule. In the "
            "combined scenario precision counts a flagged unit as correct when it carries any "
            "injected fault; a station or file carries a fault when any of its rows does.",
            "",
        ]
        rows = [
            [
                fid,
                _iv(f.get("schema_baseline_recall")),
                _iv(f.get("combined", {}).get("recall")),
                _iv(f.get("combined", {}).get("precision_any")),
            ]
            for fid, f in sorted(e1["faults"].items())
        ]
        lines += _table(
            ["Fault", "Schema baseline recall", "Combined recall", "Combined precision (any)"],
            rows,
        )
    if "e2_entity_resolution" in results:
        e2 = results["e2_entity_resolution"]
        lines += [
            "## E2: entity resolution",
            "",
            "Pairs of records from different producers placed in the same canonical crash, "
            "against pairs that share a true crash id. The naive baseline merges any two records "
            f"within {e2['naive_rule']['minutes']:g} minutes and {e2['naive_rule']['metres']:g} "
            "metres.",
            "",
        ]
        rows = []
        for scenario, s in e2["summary"].items():
            n = e2["naive_baseline"][scenario]
            rows.append(
                [
                    f"`{scenario}`",
                    _iv(s["precision"]),
                    _iv(s["recall"]),
                    _iv(s["f1"]),
                    _iv(s["abstention_rate"]),
                    _iv(s["count_error"]),
                    _iv(n["precision"]),
                    _iv(n["recall"]),
                ]
            )
        lines += _table(
            [
                "Scenario",
                "Precision",
                "Recall",
                "F1",
                "Abstention",
                "Count error",
                "Naive precision",
                "Naive recall",
            ],
            rows,
        )
    if "e3_blackspot_ranking" in results:
        e3 = results["e3_blackspot_ranking"]
        s = e3["summary"]
        lines += [
            "## E3: blackspot ranking",
            "",
            f"Top {e3['top_k']} recall of the 12 planted blackspots, over all of them and over "
            f"those with exposure (on average {s['planted_rankable']['estimate']:.1f} of 12). "
            "Coverage is the share of ranked segments whose 90 percent rank interval holds the "
            "true rank; width is in ranks.",
            "",
        ]
        rows = []
        names = {
            "raw_count": "Raw count",
            "rate": "Crash rate",
            "eb": "Empirical Bayes",
            "eb_qp": "EB with quality propagation",
        }
        for m in e3["methods"]:
            rows.append(
                [
                    names[m],
                    _iv(s[f"{m}_recall_all"]),
                    _iv(s[f"{m}_recall_rankable"]),
                    _iv(s.get(f"{m}_coverage")),
                    _iv(s.get(f"{m}_width"), 1),
                ]
            )
        lines += _table(["Method", "Recall (all)", "Recall (rankable)", "Coverage", "Width"], rows)
    if "e4_robustness" in results:
        e4 = results["e4_robustness"]
        lines += [
            "## E4: robustness",
            "",
            "Kendall tau and top 12 overlap between the ranking on the clean world and on "
            "degraded data, for Empirical Bayes and for the raw count baseline.",
            "",
        ]
        rows = []
        for scenario, s in e4["summary"].items():
            rows.append(
                [
                    f"`{scenario}`",
                    _iv(s["eb"]["kendall_tau"]),
                    _iv(s["eb"]["top_k_overlap"]),
                    _iv(s["raw_count"]["kendall_tau"]),
                    _iv(s["raw_count"]["top_k_overlap"]),
                ]
            )
        lines += _table(
            ["Scenario", "EB tau", "EB top 12 overlap", "Raw tau", "Raw top 12 overlap"], rows
        )
    if "e5_tasking" in results:
        e5 = results["e5_tasking"]
        s = e5["summary"]
        lines += [
            "## E5: tasking",
            "",
            f"Each strategy plans {e5['missions_budget']} missions with the default drone "
            f"profile. A survey adds {e5['survey_years']:g} years of crash data drawn from the "
            "hidden true rate; all strategies use the same draws. The metric is the relative "
            "reduction of the top 12 uncertainty mass, the sum of p(1 - p) over ranked "
            f"segments, recomputed with {e5['draws']} posterior draws.",
            "",
        ]
        names = {
            "value_of_information": "Value of information",
            "random": "Random",
            "greedy_crash_count": "Greedy by crash count",
        }
        rows = [
            [
                names[k],
                _iv(s[f"{k}_reduction"]),
                _iv(s[f"{k}_segments"], 1),
                _iv(s[f"{k}_flight_s"], 0),
            ]
            for k in e5["strategies"]
        ]
        lines += _table(["Strategy", "Reduction", "Segments surveyed", "Flight time (s)"], rows)
        lines += [
            f"Value of information beat random in {s['seeds_voi_beats_random']} of "
            f"{len(e5['seeds'])} seeds and greedy by crash count in "
            f"{s['seeds_voi_beats_greedy']} of {len(e5['seeds'])} seeds.",
            "",
        ]
    if "performance" in results:
        perf = results["performance"]
        lines += ["## Performance", "", perf.get("note", ""), ""]
        lines += _table(
            ["Measure", "Value", "Budget", "Within budget"],
            [
                [m["name"], m["value"], m["budget"], "yes" if m["ok"] else "no"]
                for m in perf["measures"]
            ],
        )
    notes = observations(results)
    if notes:
        lines += ["## Observations", "", "Comparisons computed from the same result files.", ""]
        lines += [f"- {n}" for n in notes] + [""]
    lines += ["## Limitations", ""] + [f"- {item}" for item in LIMITATIONS] + [""]
    return "\n".join(lines)
