"""TypeScript type generation from the contract JSON Schemas."""

from __future__ import annotations

import json
from typing import Any

from sikka.contract.schema import version_schemas
from sikka.contract.versions import CURRENT_VERSION, VERSIONS

INTERFACE_NAMES = {
    "provenance_header": "ProvenanceHeader",
    "road_segments": "RoadSegment",
    "crash_records": "CrashRecord",
    "traffic_counts": "TrafficCount",
}


def _ts_type(prop: dict[str, Any], indent: int) -> str:
    if "enum" in prop:
        return " | ".join(json.dumps(v) for v in prop["enum"])
    if "const" in prop:
        return json.dumps(prop["const"])
    kind = prop.get("type")
    if kind == "string":
        return "string"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        items = prop.get("items", {})
        if "prefixItems" in items:
            inner = ", ".join(_ts_type(p, indent) for p in items["prefixItems"])
            return f"Array<[{inner}]>"
        if "prefixItems" in prop:
            inner = ", ".join(_ts_type(p, indent) for p in prop["prefixItems"])
            return f"[{inner}]"
        return f"Array<{_ts_type(items, indent)}>"
    if kind == "object" and "properties" in prop:
        return _ts_object(prop, indent)
    return "unknown"


def _ts_object(schema: dict[str, Any], indent: int) -> str:
    required = set(schema.get("required", []))
    pad = "  " * (indent + 1)
    lines = ["{"]
    for name, prop in schema["properties"].items():
        doc = prop.get("description", "")
        unit = prop.get("x-unit")
        if unit:
            doc = f"{doc} Unit: {unit}."
        lines.append(f"{pad}/** {doc} */")
        optional = "" if name in required else "?"
        lines.append(f"{pad}readonly {name}{optional}: {_ts_type(prop, indent + 1)};")
    lines.append("  " * indent + "}")
    return "\n".join(lines)


def render_typescript() -> str:
    """Interfaces for the current version plus the list of known versions."""
    version = VERSIONS[CURRENT_VERSION]
    schemas = version_schemas(version)
    out = [
        "// Generated by `sikka docs build` from sikka.contract. Do not edit by hand.",
        f"// Contract version {CURRENT_VERSION}. Synthetic data only.",
        "",
        f'export const CONTRACT_VERSION = "{CURRENT_VERSION}";',
        "export const CONTRACT_VERSIONS = "
        + json.dumps({v.version: v.status for v in VERSIONS.values()})
        + " as const;",
        'export type FeedType = "road_segments" | "crash_records" | "traffic_counts";',
        "",
    ]
    for name, schema in schemas.items():
        out.append(f"/** {schema['title']}. */")
        out.append(f"export interface {INTERFACE_NAMES[name]} {_ts_object(schema, 0)}")
        out.append("")
    return "\n".join(out)
