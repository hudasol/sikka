"""Generated contract artefacts: JSON Schemas, bundles, field dictionary and TS types."""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any

from sikka.contract.conventions import CONVENTIONS, PROHIBITED_FIELDS, UAE_BBOX
from sikka.contract.schema import FEED_TITLES, contract_bundle, field_specs, version_schemas
from sikka.contract.typescript import render_typescript
from sikka.contract.versions import CURRENT_VERSION, VERSIONS
from sikka.core import stable_json_dumps

GENERATED_NOTE = "Generated by `sikka docs build` from `sikka.contract`. Do not edit by hand."


def _cell(value: Any) -> str:
    if value is None or value == "":
        return ""
    text = value if isinstance(value, str) else stable_json_dumps(value)
    return text.replace("|", "\\|").replace("\n", " ")


def render_field_dictionary(rules_by_field: Mapping[str, Sequence[str]]) -> str:
    """Markdown field dictionary for the current version.

    ``rules_by_field`` maps ``feed.field`` to the ids of conformance rules that
    check the field. It is supplied by the caller because rules live in a
    higher layer than the contract.
    """
    version = VERSIONS[CURRENT_VERSION]
    lines = [
        f"# Field dictionary, contract v{CURRENT_VERSION}",
        "",
        f"> {GENERATED_NOTE}",
        "",
        "This dictionary describes the open data contract that Sikka checks. Every feed in",
        "this repository is synthetic. The contract is a proposal and has not been adopted",
        "by any entity.",
        "",
        "> The Arabic descriptions are a machine drafted first version. They need review by a",
        "> native speaker before any use outside this repository.",
        "",
        "## Conventions",
        "",
        "| Topic | Convention |",
        "| --- | --- |",
    ]
    for topic, text in CONVENTIONS.items():
        lines.append(f"| {topic.replace('_', ' ')} | {_cell(text)} |")
    bbox = UAE_BBOX
    lines += [
        "",
        f"Plausible coordinates lie inside latitude {bbox['lat_min']} to {bbox['lat_max']} and "
        f"longitude {bbox['lon_min']} to {bbox['lon_max']}.",
        "",
        "## Prohibited fields",
        "",
        "These field names must never appear in a feed. Matching ignores case and separators.",
        "Records that carry them are quarantined and their values are never displayed.",
        "",
        ", ".join(f"`{name}`" for name in PROHIBITED_FIELDS),
        "",
    ]
    for name, schema in version_schemas(version).items():
        title_en, title_ar = FEED_TITLES[name]
        lines += [
            f"## {title_en} (`{name}`)",
            "",
            f"Arabic title: {title_ar}. Schema: `contract/v{CURRENT_VERSION}/{name}.schema.json`.",
            "",
            "| Field | Type | Unit | Allowed values | Required | Description | الوصف | Example "
            "| Rules |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
        ]
        for spec in field_specs(schema, name):
            rules = ", ".join(f"`{r}`" for r in rules_by_field.get(f"{name}.{spec.name}", []))
            lines.append(
                "| "
                + " | ".join(
                    [
                        f"`{spec.name}`",
                        spec.type,
                        _cell(spec.unit),
                        _cell(spec.allowed),
                        "yes" if spec.required else "no",
                        _cell(spec.description_en),
                        _cell(spec.description_ar),
                        f"`{_cell(spec.example)}`",
                        rules,
                    ]
                )
                + " |"
            )
        lines.append("")
    return "\n".join(lines)


def contract_artefacts(rules_by_field: Mapping[str, Sequence[str]]) -> dict[str, str]:
    """Every generated contract file, keyed by path relative to the repository root."""
    files: dict[str, str] = {}
    for version in VERSIONS.values():
        base = f"contract/v{version.version}"
        for name, schema in version_schemas(version).items():
            files[f"{base}/{name}.schema.json"] = stable_json_dumps(schema, indent=2) + "\n"
        files[f"{base}/contract.json"] = (
            stable_json_dumps(contract_bundle(version), indent=2) + "\n"
        )
    files["docs/CONTRACT.md"] = render_field_dictionary(rules_by_field)
    files["web/src/generated/contract.ts"] = render_typescript()
    return files
